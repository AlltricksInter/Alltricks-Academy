const cards = document.getElementById("cards");
const counter = document.getElementById("counter");

function display(data) {
  cards.innerHTML = "";
  data.forEach(item => {
    cards.innerHTML += `
      <div class="card">
        <div class="badge">${item.type}</div>
        <h3>${item.title}</h3>
        <p>${item.content}</p>
        <div class="card-actions">
          ${item.link ? `<a href="${item.link}" target="_blank" class="btn">${item.linkLabel || "Ouvrir"}</a>` : ''}
          ${item.link2 ? `<a href="${item.link2}" target="_blank" class="btn btn-alt">${item.link2Label || "Ouvrir"}</a>` : ''}
        </div>
      </div>
    `;
  });
  counter.innerHTML = data.length + " résultat(s)";
}

display(academy);

document
  .getElementById("search")
  .addEventListener("input", function () {
    const search = this.value.toLowerCase();
    const filtered = academy.filter(item =>
      item.title.toLowerCase().includes(search) ||
      item.content.toLowerCase().includes(search) ||
      item.keywords.toLowerCase().includes(search)
    );
    display(filtered);
  });